const { Router } = require('express');
const controller = require('./categories.controller');
const { asyncRoute } = require('../../shared/async-route');
const { requireAdministrator } = require('../../middlewares/require-access');
const router = Router();
router.get('/', asyncRoute(controller.list));
router.post('/', requireAdministrator, asyncRoute(controller.create));
router.put('/:id', requireAdministrator, asyncRoute(controller.update));
router.patch('/:id', requireAdministrator, asyncRoute(controller.update));
router.delete('/:id', requireAdministrator, asyncRoute(controller.remove));
module.exports = { categoriesRoutes: router };
